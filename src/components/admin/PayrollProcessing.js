import React, { useCallback, useEffect, useState } from 'react';
import {
  Alert, Box, Button, Card, CardContent, Chip, CircularProgress,
  Dialog, DialogActions, DialogContent, DialogTitle,
  IconButton, Skeleton, Table, TableBody, TableCell,
  TableContainer, TableHead, TableRow, TextField, Typography
} from '@mui/material';
import { Add, Close, Download, Payment, Refresh } from '@mui/icons-material';
import { apiRequest } from '../../utils/api';
import { getStoredUser } from '../../utils/authSession';

const fmt = (n) => Number(n || 0).toLocaleString();

const statusColor = (s) =>
  s === 'paid' ? 'success' : s === 'processed' ? 'warning' : 'default';

const downloadPayrollCSV = (payroll) => {
  const header = 'Employee,Position,Shifts,Pay Per Shift (FCFA),Total Amount (FCFA)';
  const rows = (payroll.employees || []).map(e =>
    `"${e.name || ''}","${e.position || ''}",${e.shifts || 0},${e.payPerShift || 0},${e.totalAmount || 0}`
  );
  const summary = `\n"TOTAL","","","",${payroll.totalAmount || 0}`;
  const csv = [header, ...rows, summary].join('\n');
  const blob = new Blob([csv], { type: 'text/csv' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `Payroll-${(payroll.period || 'report').replace(/\s+/g, '-')}.csv`;
  a.click();
  URL.revokeObjectURL(url);
};

